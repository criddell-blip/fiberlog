#!/usr/bin/env node
// Backfill inventory_movements.sonar_account_id for ASSET-report movements.
//
// The asset importer historically wrote only the Sonar item id into the
// movement marker ([sonar:<itemId>]) — no account. The account IS in every
// asset-report CSV (`Account | ID` beside `Model Field Data | Value List`),
// so feeding this script the report CSVs rebuilds the itemId → account map
// and emits ONE guard-safe UPDATE (sonar_account_id only — never notes,
// which sits inside the immutable-guard column list).
//
// Fiber-jobs movements don't need this: their marker embeds the account and
// migration 20260901150000 backfills them deterministically.
//
// This script never touches the DB (sage-id-backfill posture):
//
//   node scripts/backfill-sonar-accounts.mjs sql <report1.csv> [report2.csv ...]
//       Accepts any mix of asset-report CSVs — the webhook schema (item id
//       mined from `Model Field Data | Value List`) and the old manual
//       export (`Inventory Item ID` column) both work. De-dupes across
//       files, warns on item ids that map to conflicting accounts (skipped),
//       prints one UPDATE to stdout. Run the SQL via the Supabase SQL
//       editor / MCP after review.
//
// Where to get the CSVs: sonar_pending_imports.raw_csv still holds ~60 days
// of deliveries (retention migration blanks older imported rows) — export
// them to files; older history needs a re-export from Sonar's Looker report
// (any date range), fed through the same command.

import fs from 'node:fs'

// ─── CSV (same tolerant parser as lib/csvImport.js) ──────────────────────────

function parseCsv(text) {
  const rows = []
  let row = [], cell = '', q = false
  const s = text.replace(/^﻿/, '')
  for (let i = 0; i < s.length; i++) {
    const c = s[i]
    if (q) {
      if (c === '"') { if (s[i + 1] === '"') { cell += '"'; i++ } else q = false }
      else cell += c
    } else if (c === '"') q = true
    else if (c === ',') { row.push(cell); cell = '' }
    else if (c === '\n') { row.push(cell); rows.push(row); row = []; cell = '' }
    else if (c !== '\r') cell += c
  }
  if (cell !== '' || row.length) { row.push(cell); rows.push(row) }
  const [headers, ...rest] = rows.filter(r => !(r.length === 1 && r[0] === ''))
  return (rest || []).map(f => Object.fromEntries((headers || []).map((h, i) => [h, f[i] ?? ''])))
}

// Mirrors SonarImportSheet.extractItemIdFromValueList — first 3+-digit token
// of the pipe-separated Value List is the Sonar inventory item id.
function extractItemId(valueList) {
  if (!valueList) return ''
  for (const t of valueList.split('|').map(x => x.trim()).filter(Boolean)) {
    if (/^\d{3,}$/.test(t)) return t
  }
  return ''
}

// ─── main ────────────────────────────────────────────────────────────────────

const [mode, ...files] = process.argv.slice(2)
if (mode !== 'sql' || files.length === 0) {
  console.error('Usage: node scripts/backfill-sonar-accounts.mjs sql <report1.csv> [report2.csv ...]')
  process.exit(1)
}

const map = new Map()        // itemId → account
const conflicts = new Set()  // itemIds seen with >1 account (skipped)
let rowsRead = 0

for (const file of files) {
  const rows = parseCsv(fs.readFileSync(file, 'utf8'))
  for (const row of rows) {
    rowsRead++
    const account = (row['Account | ID'] || '').trim()
    if (!/^\d+$/.test(account)) continue
    const itemId = /^\d{3,}$/.test((row['Inventory Item ID'] || '').trim())
      ? row['Inventory Item ID'].trim()
      : extractItemId(row['Model Field Data | Value List'] || '')
    if (!itemId) continue
    const prev = map.get(itemId)
    if (prev && prev !== account) { conflicts.add(itemId); continue }
    map.set(itemId, account)
  }
}

for (const id of conflicts) map.delete(id)

console.error(`Read ${rowsRead} rows from ${files.length} file(s) → ${map.size} distinct item→account pairs` +
  (conflicts.size ? `; SKIPPED ${conflicts.size} conflicting item ids: ${[...conflicts].join(', ')}` : ''))

if (map.size === 0) { console.error('Nothing to emit.'); process.exit(1) }

// One statement, matched by the marker each movement already carries. Only
// fills NULLs, only writes sonar_account_id — safe past the immutable guard.
const values = [...map.entries()]
  .sort(([a], [b]) => a.localeCompare(b, undefined, { numeric: true }))
  .map(([itemId, acct]) => `  ('${itemId}', '${acct}')`)
  .join(',\n')

console.log(`-- Backfill sonar_account_id on asset-report movements, by [sonar:<itemId>] marker.
-- Generated by scripts/backfill-sonar-accounts.mjs — review, then run in the SQL editor.
update public.inventory_movements m
   set sonar_account_id = v.acct
  from (values
${values}
  ) as v(item_id, acct)
 where m.sonar_account_id is null
   and m.notes like ('%[sonar:' || v.item_id || ']%');`)
