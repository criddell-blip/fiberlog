#!/usr/bin/env node
// Backfill inventory_movements.line_note (asset tag / serial / MAC / alt tag)
// for Sonar ASSET-report movements imported before the importer wrote it.
//
// Every asset-report row carries `Model Field Data | Value List`; the first
// number in it is the asset tag the importer has always stamped as its dedup
// marker ([sonar:<tag>]). Feed this script the report CSVs and it rebuilds
// tag → line_note with the SAME parser the importer uses (lib/sonarAssetIds)
// and emits one guard-safe UPDATE — line_note only, never notes (which sits
// inside the immutable-guard column list).
//
// Idempotent + reversible: only rows with line_note IS NULL are touched, and
// `UPDATE … SET line_note = NULL WHERE notes LIKE '%[sonar:%'` undoes it.
//
// This script never touches the DB (backfill-sonar-accounts posture):
//
//   node scripts/backfill-sonar-asset-tags.mjs sql <report1.csv> [report2.csv ...] > out.sql
//
// Where to get the CSVs: sonar_pending_imports.raw_csv holds the webhook
// deliveries (export each to a file; imports/sonar-accounts/raw/ already has
// 62 of them from the Sep 1 account backfill) — older history needs a
// re-export from Sonar's Looker report, fed through the same command.

import fs from 'node:fs'
import { extractItemIdFromValueList, sonarLineNoteFromValueList } from '../src/lib/sonarAssetIds.js'

// ─── CSV (same tolerant parser as lib/csvImport.js) ──────────────────────────

function parseCsv(text) {
  const rows = []
  let row = [], cell = '', q = false
  const s = text.replace(/^﻿/, '')
  for (let i = 0; i < s.length; i++) {
    const c = s[i]
    if (q) {
      if (c === '"') { if (s[i + 1] === '"') { cell += '"'; i++ } else q = false }
      else cell += c
    } else if (c === '"') q = true
    else if (c === ',') { row.push(cell); cell = '' }
    else if (c === '\n') { row.push(cell); rows.push(row); row = []; cell = '' }
    else if (c !== '\r') cell += c
  }
  if (cell !== '' || row.length) { row.push(cell); rows.push(row) }
  const [headers, ...rest] = rows.filter(r => !(r.length === 1 && r[0] === ''))
  return (rest || []).map(f => Object.fromEntries((headers || []).map((h, i) => [h, f[i] ?? ''])))
}

const VALUE_COL = 'Model Field Data | Value List'

function sqlStr(s) { return `'${String(s).replace(/'/g, "''")}'` }

// ─── main ────────────────────────────────────────────────────────────────────

const [mode, ...files] = process.argv.slice(2)
if (mode !== 'sql' || files.length === 0) {
  console.error('usage: node scripts/backfill-sonar-asset-tags.mjs sql <report.csv> [...]')
  process.exit(2)
}

// tag → { valueList, note } — keep the LONGEST value list per tag (the
// Looker report echoes each install at several aggregation levels and the
// longest copy is the most complete one; same rule as the importer's dedup).
const byTag = new Map()
let rowsRead = 0
for (const f of files) {
  const text = fs.readFileSync(f, 'utf8')
  if (!text.trim()) continue
  const rows = parseCsv(text)
  if (rows.length && !(VALUE_COL in rows[0])) {
    console.error(`skip ${f}: no "${VALUE_COL}" column`)
    continue
  }
  for (const r of rows) {
    rowsRead++
    const vl = r[VALUE_COL] || ''
    const tag = extractItemIdFromValueList(vl)
    if (!/^\d{3,}$/.test(tag)) continue   // composite-key rows have no tag to carry
    const prev = byTag.get(tag)
    if (!prev || vl.length > prev.valueList.length) byTag.set(tag, { valueList: vl })
  }
}

const values = []
for (const [tag, { valueList }] of byTag) {
  const note = sonarLineNoteFromValueList(valueList)
  if (note) values.push(`(${sqlStr(tag)}, ${sqlStr(note)})`)
}

console.error(`Read ${rowsRead} rows from ${files.length} file(s) → ${values.length} tag → line_note pairs`)

if (values.length === 0) process.exit(0)

process.stdout.write(`-- Backfill inventory_movements.line_note from Sonar asset-report value lists.
-- Generated by scripts/backfill-sonar-asset-tags.mjs — ${values.length} tags.
-- Matches the importer's [sonar:<tag>] marker exactly (closing bracket
-- included, so tag 9285 never matches 92858) and only fills NULLs.
UPDATE public.inventory_movements m
SET line_note = v.note
FROM (VALUES
  ${values.join(',\n  ')}
) AS v(tag, note)
WHERE m.line_note IS NULL
  AND m.notes LIKE '%[sonar:' || v.tag || ']%';
`)
